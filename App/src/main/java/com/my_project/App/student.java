package com.my_project.App;

public class student {
    public Long id;
    public String name;
    public Long age;
    public String course;

    public student() {

    }

    public Long getId() {
        return id;
    }
    public String getName() {
        return name;
    }
    public Long getAge() {
        return age;
    }
    public String getCourse() {
        return course;
    }
    public void setId() {
        this.id=id;
    }
    public void setName() {
        this.name=name;
    }
    public void setAge() {
        this.age=age;
    }
    public void setCourse() {
        this.course=course;
    }
}
